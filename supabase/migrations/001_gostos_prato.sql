-- =============================================================================
-- 001 — Gostos dos pratos (PostgreSQL / Supabase)
-- =============================================================================
-- Reproduz src/db/migrations/001_gostos_prato.sql.
-- Idempotente: pode ser executado depois do 000 sem efeitos duplicados.
--
-- Não é criada a função RPC `alternar_gosto` do ficheiro de referência SQLite:
-- a aplicação trata os gostos diretamente no servidor e, com RLS ativa e sem
-- políticas públicas, não deve existir uma função SECURITY DEFINER exposta.
-- =============================================================================

-- Contador denormalizado no prato (já existe no 000; mantido por compatibilidade)
ALTER TABLE pratos ADD COLUMN IF NOT EXISTS gostos INTEGER NOT NULL DEFAULT 0;

-- Um gosto por prato e por sessão de mesa (o cliente só pode gostar uma vez).
CREATE TABLE IF NOT EXISTS gostos_prato (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  prato_id BIGINT NOT NULL REFERENCES pratos(id) ON DELETE CASCADE,
  sessao_id BIGINT NOT NULL REFERENCES sessoes_mesa(id) ON DELETE CASCADE,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (prato_id, sessao_id)
);

CREATE INDEX IF NOT EXISTS idx_gostos_prato ON gostos_prato(prato_id);
CREATE INDEX IF NOT EXISTS idx_gostos_sessao ON gostos_prato(sessao_id);

-- Reconcilia o contador com a tabela (protege dados antigos).
UPDATE pratos
SET gostos = (
  SELECT COUNT(*)
  FROM gostos_prato
  WHERE gostos_prato.prato_id = pratos.id
);
